import { describe, expect, it } from 'vitest';
import referans from './referans/fsrs-referans.json' with { type: 'json' };
import {
  Derece,
  Durum,
  ayarlariDogrula,
  hatirlanabilirlik,
  incele,
  onizle,
  simdikiHatirlanabilirlik,
  takvimGunuFarki,
  vadesiGeldiMi,
  varsayilanAgirliklar,
  varsayilanAyarlar,
  yeniKart,
  type Ayarlar,
  type KartDurumu,
} from './fsrs.ts';

const utcAyar = (hedef: number): Ayarlar => ({
  ...varsayilanAyarlar,
  hedefHatirlama: hedef,
  gunKaydirmaDk: 0,
});
const T0 = new Date('2026-11-07T09:00:00.000Z');

describe('FSRS-6 against reference results of ts-fsrs 6.0.0 (MIT)', () => {
  it('uses the reference scenario set generated by uret-fsrs-referans.mjs', () => {
    expect(referans.kaynak).toBe('ts-fsrs@6.0.0');
    expect(referans.senaryolar).toHaveLength(8);
  });

  referans.senaryolar.forEach((senaryo, n) => {
    it(`scenario ${n + 1}: ${senaryo.adimlar.length} reviews at retention ${senaryo.hedefHatirlama} match to eight decimals`, () => {
      const ayar = utcAyar(senaryo.hedefHatirlama);
      let kart: KartDurumu = yeniKart(new Date(senaryo.baslangic));
      for (const adim of senaryo.adimlar) {
        const simdi = new Date(adim.simdi);
        const secenekler = onizle(kart, simdi, ayar);
        for (const g of [1, 2, 3, 4] as const) {
          expect(secenekler[g].scheduledDays).toBe(adim.onizleme[String(g) as '1']);
        }
        kart = incele(kart, adim.derece as Derece, simdi, ayar);
        expect(kart.due.toISOString()).toBe(adim.sonuc.due);
        expect(kart.stability).toBeCloseTo(adim.sonuc.stability, 8);
        expect(kart.difficulty).toBeCloseTo(adim.sonuc.difficulty, 8);
        expect(kart.scheduledDays).toBe(adim.sonuc.scheduledDays);
        expect(kart.reps).toBe(adim.sonuc.reps);
        expect(kart.lapses).toBe(adim.sonuc.lapses);
        expect(kart.state).toBe(adim.sonuc.state);
      }
    });
  });
});

describe('first review of a new card (default weights, 90 percent retention)', () => {
  const sonuc = onizle(yeniKart(T0), T0, utcAyar(0.9));
  it('starts stability at w0..w3 and difficulty from w4 and w5', () => {
    expect(sonuc[1].stability).toBeCloseTo(varsayilanAgirliklar[0] as number, 4);
    expect(sonuc[2].stability).toBeCloseTo(varsayilanAgirliklar[1] as number, 4);
    expect(sonuc[3].stability).toBeCloseTo(varsayilanAgirliklar[2] as number, 4);
    expect(sonuc[4].stability).toBeCloseTo(varsayilanAgirliklar[3] as number, 4);
    // D0(G) = w4 - exp(w5 (G - 1)) + 1, clamped to [1, 10]
    expect(sonuc[1].difficulty).toBeCloseTo(6.4133 - Math.exp(0) + 1, 6);
    expect(sonuc[3].difficulty).toBeCloseTo(6.4133 - Math.exp(2 * 0.8334) + 1, 6);
  });
  it('gives whole day intervals that rise strictly with the rating', () => {
    const gunler = [1, 2, 3, 4].map((g) => sonuc[g as Derece].scheduledDays);
    expect(gunler).toEqual([1, 2, 3, 8]);
  });
  it('puts every rated card in the Review state and counts no lapse for a new card', () => {
    for (const g of [1, 2, 3, 4] as const) {
      expect(sonuc[g].state).toBe(Durum.Gozden);
      expect(sonuc[g].lapses).toBe(0);
      expect(sonuc[g].reps).toBe(1);
      expect(sonuc[g].lastReview).toEqual(T0);
    }
  });
});

describe('scheduling properties', () => {
  it('lowers the retrievability to exactly the target at the scheduled interval', () => {
    const w = varsayilanAgirliklar;
    // With stability s, the interval for retention R satisfies R(t, s) = R (up to interval rounding).
    for (const s of [1, 5, 30, 200]) {
      const aralik = Math.max(
        Math.round((s / bozunumFaktoru(w)) * (Math.pow(0.9, 1 / -(w[20] as number)) - 1)),
        1,
      );
      expect(hatirlanabilirlik(aralik, s, w)).toBeGreaterThan(0.88);
      expect(hatirlanabilirlik(aralik, s, w)).toBeLessThan(0.92);
    }
    expect(hatirlanabilirlik(0, 10)).toBe(1);
  });

  it('counts a lapse only for a card that was already in Review', () => {
    let k = incele(yeniKart(T0), Derece.Iyi, T0, utcAyar(0.9));
    const sonra = new Date(T0.getTime() + 5 * 86_400_000);
    k = incele(k, Derece.Tekrar, sonra, utcAyar(0.9));
    expect(k.lapses).toBe(1);
    expect(k.scheduledDays).toBeGreaterThanOrEqual(1);
  });

  it('never lets a failed review raise stability and never lets intervals shrink with better ratings', () => {
    let k = incele(yeniKart(T0), Derece.Kolay, T0, utcAyar(0.9));
    for (let i = 1; i <= 6; i++) {
      const simdi = new Date(k.due.getTime());
      const o = onizle(k, simdi, utcAyar(0.9));
      expect(o[1].stability).toBeLessThanOrEqual(k.stability);
      expect(o[1].scheduledDays).toBeLessThan(o[2].scheduledDays);
      expect(o[2].scheduledDays).toBeLessThan(o[3].scheduledDays);
      expect(o[3].scheduledDays).toBeLessThan(o[4].scheduledDays);
      k = o[3];
    }
  });

  it('keeps difficulty within 1 and 10 under repeated ratings', () => {
    let k = yeniKart(T0);
    let t = T0;
    for (let i = 0; i < 60; i++) {
      k = incele(k, (i % 7 < 5 ? 1 : 4) as Derece, t, utcAyar(0.9));
      t = new Date(t.getTime() + 86_400_000);
      expect(k.difficulty).toBeGreaterThanOrEqual(1);
      expect(k.difficulty).toBeLessThanOrEqual(10);
    }
  });

  it('caps an interval at the maximum interval', () => {
    const ayar = { ...utcAyar(0.9), enFazlaAralik: 30 };
    let k = incele(yeniKart(T0), Derece.Kolay, T0, ayar);
    for (let i = 0; i < 6; i++) k = incele(k, Derece.Kolay, k.due, ayar);
    expect(k.scheduledDays).toBeLessThanOrEqual(30);
  });

  it('gives a higher retention target shorter intervals', () => {
    const iyi = incele(yeniKart(T0), Derece.Iyi, T0, utcAyar(0.9));
    const a97 = incele(iyi, Derece.Iyi, iyi.due, utcAyar(0.97));
    const a80 = incele(iyi, Derece.Iyi, iyi.due, utcAyar(0.8));
    expect(a97.scheduledDays).toBeLessThan(a80.scheduledDays);
  });

  it('is deterministic: the same history gives the same state', () => {
    const calistir = () => {
      let k = yeniKart(T0);
      let t = T0;
      for (const g of [3, 3, 1, 2, 4, 3] as const) {
        t = new Date(t.getTime() + 4 * 86_400_000);
        k = incele(k, g, t);
      }
      return k;
    };
    expect(calistir()).toEqual(calistir());
  });
});

describe('Turkish calendar day', () => {
  it('counts 23:30 and 00:30 local time as consecutive days, which UTC does not', () => {
    // 20:30Z is 23:30 in Turkey; 21:30Z is 00:30 the next day in Turkey.
    const a = new Date('2026-11-07T20:30:00Z');
    const b = new Date('2026-11-07T21:30:00Z');
    expect(takvimGunuFarki(a, b, 180)).toBe(1);
    expect(takvimGunuFarki(a, b, 0)).toBe(0);
  });
  it('treats a card due earlier today as due, and tomorrow as not yet due', () => {
    let k = incele(yeniKart(T0), Derece.Iyi, T0);
    expect(vadesiGeldiMi(k, T0)).toBe(false);
    const vade = new Date(k.due.getTime());
    expect(vadesiGeldiMi(k, vade)).toBe(true);
    expect(vadesiGeldiMi(k, new Date(vade.getTime() + 3_600_000))).toBe(true);
    k = { ...k, due: new Date(T0.getTime() + 2 * 86_400_000) };
    expect(vadesiGeldiMi(k, T0)).toBe(false);
    expect(vadesiGeldiMi(yeniKart(T0), T0)).toBe(false);
  });
  it('reports retrievability only for reviewed cards', () => {
    expect(simdikiHatirlanabilirlik(yeniKart(T0), T0)).toBeNull();
    const k = incele(yeniKart(T0), Derece.Iyi, T0);
    expect(simdikiHatirlanabilirlik(k, new Date(T0.getTime() + 86_400_000))).toBeLessThan(1);
  });
});

describe('input validation', () => {
  it('rejects out of range settings and ratings', () => {
    expect(() => ayarlariDogrula({ ...varsayilanAyarlar, hedefHatirlama: 0.5 })).toThrow(RangeError);
    expect(() => ayarlariDogrula({ ...varsayilanAyarlar, hedefHatirlama: 1 })).toThrow(RangeError);
    expect(() => ayarlariDogrula({ ...varsayilanAyarlar, agirliklar: [1, 2, 3] })).toThrow(RangeError);
    expect(() => ayarlariDogrula({ ...varsayilanAyarlar, enFazlaAralik: 0 })).toThrow(RangeError);
    expect(() => incele(yeniKart(T0), 5 as Derece, T0)).toThrow(RangeError);
    expect(() => incele(yeniKart(T0), 0 as Derece, T0)).toThrow(RangeError);
  });
  it('defaults to a 90 percent target as plan 10.6/2 says', () => {
    expect(varsayilanAyarlar.hedefHatirlama).toBe(0.9);
    expect(varsayilanAgirliklar).toHaveLength(21);
  });
});

function bozunumFaktoru(w: readonly number[]) {
  const decay = -(w[20] as number);
  return Math.round((Math.exp(Math.log(0.9) / decay) - 1) * 1e8) / 1e8;
}
